_CatBook _cat(String slug) => _catalog.firstWhere((b) => b.slug == slug);

/// Ảnh bìa của ấn bản [ed] (vượt số ấn bản thì lấy ấn bản đầu).
String _coverOf(String slug, int ed) {
  final eds = _cat(slug).eds;
  return eds[ed < eds.length ? ed : 0].cover;
}

/// Sách trong kho mẫu → `Book` với ảnh bìa thật.
Book _catBook(
  String slug,
  int ed, {
  required String id,
  ConditionGrade cond = ConditionGrade.good,
  String? description,
}) {
  final b = _cat(slug);
  final e = b.eds[ed < b.eds.length ? ed : 0];
  return Book(
    id: id,
    title: b.title,
    author: b.author,
    condition: cond,
    images: [BookImage(url: e.cover)],
    publisher: b.publisher,
    publishYear: b.year,
    pages: b.pages,
    language: 'Tiếng Việt',
    categoryId: b.cat,
    categoryName: _catNames[b.cat],
    description:
        description ?? (e.note.isEmpty ? b.desc : '${b.desc} ${e.note}.'),
    weightGram: 200 + b.pages,
  );
}
